const WORD_RULES = RULES.map(([keys, emoji]) => ({
  emoji,
  res: keys.map((k) => new RegExp(`(^|[^a-z])${norm(k).replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`)),
}));

/** Emoji del producto según su nombre, o null si no lo reconocemos (la UI muestra la inicial). */
export function emojiForProduct(name: string): string | null {
  const n = norm(name);
  for (const r of WORD_RULES) if (r.res.some((re) => re.test(n))) return r.emoji;
  return null;
}
